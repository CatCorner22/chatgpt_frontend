export function cardMarkdown(c: Card) {
  return [
    `### ${c.name} (evidence ${c.grade})`,
    `- Purpose: ${c.purpose}`,
    `- Use: ${c.use}`,
    `- Avoid: ${c.avoid}`,
    c.states && `- States: ${c.states}`,
    c.behavior && `- Behavior: ${c.behavior}`,
    c.writing && `- Writing: ${c.writing}`,
    `- Floor: ${c.floor}`,
    `- Common AI mistake: ${c.mistakes}`,
  ]
    .filter(Boolean)
    .join("\n");
}
